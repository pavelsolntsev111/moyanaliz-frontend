// расследование аварии по ложному следу.
// Живость системы проверять через /api/v1/ping (реально доезжает до бэкенда)
// или /health/deep на самом бэкенде (Mongo + S3).
//
// Путь менять НЕЛЬЗЯ без синхронной правки HEALTHCHECK в Dockerfile — иначе
// Timeweb сочтёт контейнер больным и уронит фронт в рестарт-петлю.
