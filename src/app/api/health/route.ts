// liveness фронт-контейнера, а не readiness всей системы: фронт не должен
// перезапускаться из-за недоступного бэкенда.
//
// ⚠️ НЕ ИСПОЛЬЗОВАТЬ КАК ПРОВЕРКУ ЖИВОСТИ СЕРВИСА. Роут перехватывает путь ДО
